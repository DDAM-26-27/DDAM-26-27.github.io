/** Bundles server/edge.ts into a single file for Supabase Edge Functions (Deno). */
import { builtinModules } from 'node:module';
import { build } from 'esbuild';

const builtins = new Set(builtinModules);
await build({
  entryPoints: ['server/edge.ts'],
  outfile: 'supabase/functions/api/index.js',
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  mainFields: ['module', 'main'],
  conditions: ['import', 'default'],
  banner: {
    // The Supabase Edge Runtime does not define Node's globals (Buffer, process, setImmediate, …),
    // which postgres.js uses. Provide them from Deno's node: compatibility modules.
    js: [
      '// Generated by `npm run build:edge` from server/edge.ts. Do not edit.',
      'import { Buffer as __Buffer } from "node:buffer";',
      'import __process from "node:process";',
      'import { setImmediate as __setImmediate, clearImmediate as __clearImmediate } from "node:timers";',
      'globalThis.global ??= globalThis;',
      'globalThis.Buffer ??= __Buffer;',
      'globalThis.process ??= __process;',
      'globalThis.setImmediate ??= __setImmediate;',
      'globalThis.clearImmediate ??= __clearImmediate;',
    ].join('\n'),
  },
  plugins: [
    {
      name: 'node-builtins',
      setup(b) {
        // Deno needs the explicit node: prefix for Node built-ins.
        b.onResolve({ filter: /^[a-z_]+$/ }, (args) =>
          builtins.has(args.path) ? { path: `node:${args.path}`, external: true } : undefined,
        );
        b.onResolve({ filter: /^node:/ }, (args) => ({ path: args.path, external: true }));
      },
    },
  ],
});
console.log('built supabase/functions/api/index.js');
